"""The evaluation report: the rules baseline and the workflow on the development cases, kept apart."""

import platform
import tempfile
from collections import Counter
from pathlib import Path

from .desk import FIXTURES, Desk, load_fixture
from .proposer import ScriptedProposer
from .workflow import Workbench


def evaluate(desk: Desk, proposer, cases: dict) -> list[dict]:
    """Every case through the real graph, in a scratch state directory, as far as its first person."""
    rows = []
    with tempfile.TemporaryDirectory() as scratch, Workbench(Path(scratch), desk, proposer) as bench:
        for case in cases["cases"]:
            status = bench.start(case["claim_id"])
            rows.append({"case": case, "state": status["state"], **status["values"]})
    return rows


def expected(row: dict) -> tuple:
    return row["case"]["decision"], row["case"]["amount"]


def from_rules(row: dict) -> tuple:
    return row["baseline"]["decision"], row["baseline"]["amount"]


def from_proposal(row: dict) -> tuple:
    proposal = row["proposal"]
    return (proposal["decision"], proposal["amount"]) if proposal else ("no valid proposal", None)


def score(rows: list[dict], decided, routed) -> dict:
    return {
        "decision": sum(decided(row) == expected(row) for row in rows),
        "route": sum(routed(row) == row["case"]["route"] for row in rows),
        "wrongly_automatic": [row["claim_id"] for row in rows if routed(row) == "auto" and row["case"]["route"] == "review"],
        "needlessly_to_a_person": [row["claim_id"] for row in rows if routed(row) == "review" and row["case"]["route"] == "auto"],
    }


def said(decision: tuple) -> str:
    return " ".join(part for part in decision if part)


def build_report(desk: Desk | None = None, proposer=None, cases: dict | None = None,
                 state_dir: Path | None = None) -> str:
    desk = desk or Desk.load()
    proposer = proposer or ScriptedProposer.load()
    cases, cases_fingerprint = (cases, "supplied") if cases else load_fixture("cases.json", FIXTURES)
    rows = evaluate(desk, proposer, cases)
    total = len(rows)
    rules = score(rows, from_rules, lambda row: row["baseline"]["route"])
    workflow = score(rows, from_proposal, lambda row: row["route"])
    versions = rows[0]["versions"]
    listed = lambda ids: f"{len(ids)}" + (f" ({', '.join(ids)})" if ids else "")

    lines = [
        "# Warranty review: evaluation report",
        "",
        f"Generated by `python -m warranty_review report`. Development cases only: `fixtures/cases.json`, {total} cases, "
        "written with their expected answers before the workflow ran, by the same author. There is no held-out set.",
        "",
        "No model was called. Every proposal comes from `fixtures/scripted_replies.json`, written by hand to exercise "
        "the checks, and several are wrong on purpose. These figures test the workflow's routing and controls; "
        "they say nothing about any model.",
        "",
        "## Versions and environment",
        "",
        f"- Example {versions['example']}; prompt {versions['prompt']} (template {versions['prompt_template']}); "
        f"proposer {versions['proposer']}",
        f"- Fixtures: desk {versions['desk']}, cases {cases_fingerprint}",
        f"- Python {platform.python_version()} on {platform.platform()}; langgraph {versions['langgraph']}, "
        f"langgraph-checkpoint-sqlite {versions['langgraph-checkpoint-sqlite']}",
        "",
        "## Baseline and workflow",
        "",
        "| Measure | Rules baseline, no model | Workflow: scripted proposal, checks in code |",
        "| --- | --- | --- |",
        f"| Decision and amount as expected | {rules['decision']}/{total} | {workflow['decision']}/{total} |",
        f"| Route as expected | {rules['route']}/{total} | {workflow['route']}/{total} |",
        f"| Decided without a person when a person was expected | {listed(rules['wrongly_automatic'])} "
        f"| {listed(workflow['wrongly_automatic'])} |",
        f"| Sent to a person when none was expected | {listed(rules['needlessly_to_a_person'])} "
        f"| {listed(workflow['needlessly_to_a_person'])} |",
        "",
        "For the workflow, the decision measured is the proposal's. Where the route is a person, the final decision is "
        "theirs; this report does not invent reviewers' decisions.",
        "",
        "## Cases",
        "",
        "| Case | Expected | Rules | Rules route | Proposal | Failed checks | Why a person | Workflow route | Scratch run |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in rows:
        failed = "; ".join(check["name"] for check in row["checks"] if not check["ok"]) or "none"
        outcome = row.get("outcome")
        scratch = (f"{said((outcome['decision'], outcome['amount']))}, {outcome['decided_by']}"
                   if outcome else row["state"])
        lines.append(f"| {row['claim_id']} | {said(expected(row))}, {row['case']['route']} | {said(from_rules(row))} "
                     f"| {row['baseline']['route']} | {said(from_proposal(row))} | {failed} "
                     f"| {'; '.join(row['flags']) or 'none'} | {row['route']} | {scratch} |")

    if state_dir is not None:
        lines += ["", f"## Recorded outcomes in `{state_dir.name}/`", ""]
        with Workbench(state_dir, desk, proposer) as bench:
            payments, reviews = bench.records.payments(), bench.records.reviews()
            per_claim = Counter(payment["claim_id"] for payment in payments)
            for claim_id in desk.data["claims"]:
                status = bench.status(claim_id)
                if status["state"] == "not started":
                    continue
                outcome = status["values"].get("outcome")
                decided = f": {said((outcome['decision'], outcome['amount']))}, decided by {outcome['decided_by']}" if outcome else ""
                counted = [review["status"] for review in reviews if review["claim_id"] == claim_id]
                lines.append(f"- {claim_id} {status['state']}{decided}; payments {per_claim[claim_id]}; "
                             f"reviews {len(counted)}" + (f" ({', '.join(counted)})" if counted else ""))
            doubled = sorted(claim_id for claim_id, count in per_claim.items() if count > 1)
            lines.append(f"- Claims paid more than once: {', '.join(doubled) if doubled else 'none'}")

    lines += ["", "## Assumptions", ""]
    lines += [f"- {key}: {text}" for key, text in cases["assumptions"].items()]
    lines += ["", "## Unresolved questions", ""]
    lines += [f"- {key}: {text}" for key, text in cases["unresolved"].items()]
    lines += [
        "",
        "## What this report does not show",
        "",
        "- How any model would do. No model ran, and the scripted replies were chosen by the author.",
        "- How the workflow would do on new claims. The cases are development cases, not a held-out set.",
        "- An improvement loop. Nothing here changes the prompt, the rules or the code from these results.",
        "- Other platforms. Only the environment named above ran it.",
        "",
    ]
    return "\n".join(lines)
